<?php

declare(strict_types=1);

/**
 * Writes lang/en/items.php: the real Kobo form's wording for every scored item, so the facility
 * drawer names an item by what the assessor was asked rather than its code. Read-only on the form:
 * it reads the version's content as discovery/kobo_forms.py saved it (data/forms/kobo/, not
 * committed) and the item rules (config/edqa_item_rules.php), and writes only the lang file.
 *
 * - choice and count3 items: the question's own label;
 * - match items (three numbers compared, D-68): the data element named in the note before the
 *   first number, without the month marker the form puts in front of it.
 *
 * Markup and ${…} placeholders are removed; whitespace is collapsed. An item whose question cannot
 * be found stops the run: the file is all or nothing.
 *
 * Usage (from the project root, no network):
 *   php discovery/kobo_item_labels.php [version-uid] [map]
 *   php discovery/kobo_item_labels.php vBnJSJRKjVuT4yDaRhKXye kobo-2024010101
 */
$root = dirname(__DIR__);
$version = $argv[1] ?? 'vBnJSJRKjVuT4yDaRhKXye';
$map = $argv[2] ?? 'kobo-2024010101';

$file = "{$root}/discovery/data/forms/kobo/{$version}.content.json";
if (! is_file($file)) {
    fwrite(STDERR, "No form content at {$file}: run discovery/kobo_forms.py first.\n");
    exit(1);
}
$content = json_decode((string) file_get_contents($file), true, flags: JSON_THROW_ON_ERROR);
$survey = $content['content']['survey'] ?? $content['survey'] ?? [];
$rules = (require "{$root}/config/edqa_item_rules.php")[$map] ?? null;
if (! is_array($rules) || $survey === []) {
    fwrite(STDERR, "No item rules for map {$map}, or no survey rows in the form.\n");
    exit(1);
}

// Row index by question path, as the rules name it (dots) and the form stores it ($xpath, slashes).
$byPath = [];
foreach ($survey as $i => $row) {
    if (isset($row['$xpath'])) {
        $byPath[str_replace('/', '.', (string) $row['$xpath'])] = $i;
    }
}

$text = function (mixed $label, bool $dropSpans): string {
    $s = is_array($label) ? (string) ($label[0] ?? '') : (string) $label;
    if ($dropSpans) {
        $s = (string) preg_replace('#<span\b[^>]*>.*?</span>#is', ' ', $s); // the month marker
    }
    $s = strip_tags($s);
    $s = (string) preg_replace('/\$\{[^}]*\}/', ' ', $s);
    $s = html_entity_decode($s, ENT_QUOTES | ENT_HTML5);

    return trim((string) preg_replace('/\s+/u', ' ', $s));
};

$labels = ['availability' => [], 'consistency' => [], 'validity' => []];
$problems = [];
foreach ($rules as $rule) {
    $first = $rule['paths'][0] ?? null;
    $i = $first === null ? null : ($byPath[$first] ?? null);
    if ($i === null) {
        $problems[] = "{$rule['dimension']}.{$rule['code']}: {$first} is not in the form";

        continue;
    }
    if ($rule['kind'] === 'match') {
        $label = '';
        for ($j = $i - 1; $j >= 0 && $label === ''; $j--) {
            if (($survey[$j]['type'] ?? '') === 'note') {
                $label = $text($survey[$j]['label'] ?? '', true);
            }
        }
    } else {
        $label = $text($survey[$i]['label'] ?? '', false);
    }
    if ($label === '') {
        $problems[] = "{$rule['dimension']}.{$rule['code']}: no wording found";

        continue;
    }
    $labels[$rule['dimension']][$rule['code']] = $label;
}

if ($problems !== []) {
    fwrite(STDERR, count($problems)." item(s) without wording; nothing written:\n  ".implode("\n  ", array_slice($problems, 0, 20))."\n");
    exit(1);
}

$out = "<?php\n\ndeclare(strict_types=1);\n\n"
    ."// The real Kobo form's wording for each scored item (ARCHITECTURE.md §5.5), shown in the facility\n"
    ."// drawer. GENERATED by discovery/kobo_item_labels.php from {$version}.content.json (map {$map});\n"
    ."// regenerate, do not edit. The wording is the client's, as the form asks it.\n\n"
    ."return [\n";
foreach ($labels as $dimension => $items) {
    $out .= "    '{$dimension}' => [\n";
    foreach ($items as $code => $label) {
        $out .= '        '.var_export((string) $code, true).' => '.var_export($label, true).",\n";
    }
    $out .= "    ],\n";
}
$out .= "];\n";
file_put_contents("{$root}/lang/en/items.php", $out);

printf("Wrote lang/en/items.php: %d availability, %d consistency, %d validity labels from %s.\n",
    count($labels['availability']), count($labels['consistency']), count($labels['validity']), $version);
